#!/usr/bin/env python3
"""Build downloadable content packs (D-112, D-99): one data-only Godot pck per game/packs/<id>/.

A pack source folder (a chapter is moved into a pack by moving its data here, no code changes):

  game/packs/<id>/pack.json            {"schema": "lockwright.content_pack/1", "id", "version",
                                        "min_game", "chapters": [13], "jobs": {...}}
  game/packs/<id>/jobs/<job id>.json   the jobs (schema of game/data/jobs)
  game/packs/<id>/i18n/content.csv     their texts: keys,en,pl,de,fr,es (+ content.csv.import, compress=0;
                                        the .translation files are made by Godot's import, not committed)
  game/packs/<id>/arrival_scenes.json  optional, schema of game/data/arrival_scenes.json; every `dir`
                                        under res://packs/<id>/
  game/packs/<id>/arrival/...          frames and plates (webp + their .import), any layout

`jobs` in pack.json ({job id: {chapter, family, tier}}) is derived from jobs/*.json: `--sync` writes
it (and sets compress=0 in a freshly imported content.csv.import), every other run checks it. It is what the game keeps about a job whose pack is not on the phone.

The pck is exported by Godot with a preset generated for the build ("Content <id>": only
packs/<id>/*, no scripts) and then checked to be data only (store policy: downloaded content must
not change code): only files under res://packs/<id>/ with data extensions, their imported forms in
res://.godot/imported/ and Godot's housekeeping files are allowed. The game mounts it without
replacing files, so a pack can only add res://packs/<id>/.

Outputs in --out: content_<id>.pck, content_<id>.json (the pack's entry) and content_packs.json
(the game's list of every pack: file, url, size, sha256, version, min_game, chapters, jobs).
One GitHub Release per pack version: tag `content-<id>-v<version>`. The pck bytes are not
reproducible across game commits, so a released version is never rebuilt: pass the entries of
existing releases with --released DIR (content_<id>.json files); a pack whose sources changed
without a new `version` in pack.json is an error.

Usage (from the repo root):
  python3 tools/build_content_packs.py --check                 # validate the sources (no Godot)
  python3 tools/build_content_packs.py --sync                  # rewrite `jobs` in every pack.json
  python3 tools/build_content_packs.py --list                  # "<id> <version> <tag>" per pack
  python3 tools/build_content_packs.py --godot G [--import] [--packs ch13] [--out game/build/content]
      [--released DIR] [--base-url URL] [--write-game-manifest]
`--base-url` may contain `{tag}`; default: GitHub Releases of this repository (env
CONTENT_PACKS_BASE_URL overrides).
"""
import argparse
import csv
import hashlib
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_voice_packs import HOUSEKEEPING, read_pck_paths, sha256_file  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(ROOT, "game")
PACKS = os.path.join(GAME, "packs")
PRESETS = os.path.join(GAME, "export_presets.cfg")
GAME_MANIFEST = os.path.join(GAME, "data", "content_packs.json")
BASE_JOBS = os.path.join(GAME, "data", "jobs")
BASE_CSV = [os.path.join(GAME, "i18n", "strings.csv"), os.path.join(GAME, "i18n", "content.csv")]
DEFAULT_BASE_URL = "https://github.com/woogitsugames/lockwright/releases/download/{tag}"
PACK_SCHEMA = "lockwright.content_pack/1"
SCHEMA = 1
ID_RE = re.compile(r"^[a-z][a-z0-9_]{0,31}$")
JOB_RE = re.compile(r"^job\.[a-z0-9_]+$")
LANGS = ["en", "pl", "de", "fr", "es"]
# What a pack source folder may hold. Imported kinds need their .import next to them.
IMPORTED_EXT = {".webp", ".png", ".jpg", ".ogg", ".csv"}
SOURCE_EXT = IMPORTED_EXT | {".json", ".import", ".translation"}
# What the pck may hold under res://packs/<id>/ (the raw .csv is replaced by its .translation files).
PCK_EXT = {".json", ".import", ".translation", ".webp", ".png", ".jpg", ".ogg"}
IMPORTED_RE = re.compile(r"^res://\.godot/imported/(.+)-([0-9a-f]{32})\.(ctex|oggvorbisstr|sample)$")
PRESET_TEMPLATE = '''
[preset.{n}]
; D-112: generated by tools/build_content_packs.py for this build only (not committed).
name="Content {id}"
platform="Linux"
runnable=false
export_filter="resources"
export_files=PackedStringArray()
include_filter="packs/{id}/*"
exclude_filter="*.gd,*.gdshader,*.gdshaderinc,*.svg,*.gdextension,*.tscn,*.scn,*.tres,*.res"
export_path="build/content/content_{id}.pck"
encryption_include_filters=""
encryption_exclude_filters=""
encrypt_pck=false
encrypt_directory=false

[preset.{n}.options]

binary_format/embed_pck=false
'''


def tag_for(pack_id, version):
    return "content-%s-v%d" % (pack_id, version)


def discover(packs_dir=PACKS):
    if not os.path.isdir(packs_dir):
        return []
    return sorted(d for d in os.listdir(packs_dir)
                  if os.path.isfile(os.path.join(packs_dir, d, "pack.json")))


def source_files(pack_dir):
    """Relative paths (posix) of every file in the pack source folder."""
    out = []
    for base, _dirs, files in os.walk(pack_dir):
        for f in files:
            out.append(os.path.relpath(os.path.join(base, f), pack_dir).replace(os.sep, "/"))
    return sorted(out)


def derive_jobs(pack_dir):
    """{job id: {chapter, family, tier}} from jobs/*.json, plus the errors found on the way."""
    jobs, errors = {}, []
    jdir = os.path.join(pack_dir, "jobs")
    for name in sorted(os.listdir(jdir)) if os.path.isdir(jdir) else []:
        if not name.endswith(".json"):
            continue
        try:
            with open(os.path.join(jdir, name), encoding="utf-8") as f:
                job = json.load(f)
        except (OSError, ValueError) as e:
            errors.append("jobs/%s: %s" % (name, e))
            continue
        jid = job.get("id", "") if isinstance(job, dict) else ""
        if jid + ".json" != name or not JOB_RE.match(jid):
            errors.append("jobs/%s: file must be named after its id (job.<name>.json), id is %r" % (name, jid))
            continue
        if not isinstance(job.get("chapter"), int) or isinstance(job.get("chapter"), bool):
            errors.append("jobs/%s: chapter must be an integer" % name)
            continue
        jobs[jid] = {"chapter": job["chapter"], "family": str(job.get("family", "")),
                     "tier": max(1, int(job.get("tier", 1)))}
    return jobs, errors


def csv_keys(path):
    with open(path, encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f))
    return (rows[0] if rows else []), [r[0] for r in rows[1:] if r and r[0]]


def check_source(pack_id, pack_dir, base_jobs=BASE_JOBS, base_csv=BASE_CSV):
    """Errors in a pack source folder (empty list: it can be built)."""
    errors = []
    if not ID_RE.match(pack_id):
        return ["%s: bad pack id (a-z, 0-9, _; starts with a letter; at most 32)" % pack_id]
    try:
        with open(os.path.join(pack_dir, "pack.json"), encoding="utf-8") as f:
            pack = json.load(f)
    except (OSError, ValueError) as e:
        return ["pack.json: %s" % e]
    if not isinstance(pack, dict):
        return ["pack.json: not an object"]
    if pack.get("schema") != PACK_SCHEMA:
        errors.append("pack.json: schema must be %s" % PACK_SCHEMA)
    if pack.get("id") != pack_id:
        errors.append("pack.json: id must be the folder name (%s)" % pack_id)
    for key in ("version", "min_game"):
        if not isinstance(pack.get(key), int) or isinstance(pack.get(key), bool) or pack[key] < 1:
            errors.append("pack.json: %s must be an integer >= 1" % key)
    chapters = pack.get("chapters")
    if not isinstance(chapters, list) or not chapters or \
            any(not isinstance(c, int) or isinstance(c, bool) or c < 1 for c in chapters):
        errors.append("pack.json: chapters must be a non-empty list of integers >= 1")
        chapters = []
    jobs, job_errors = derive_jobs(pack_dir)
    errors += job_errors
    if not jobs:
        errors.append("jobs/: a pack needs at least one job")
    if pack.get("jobs") != jobs:
        errors.append("pack.json: `jobs` does not match jobs/*.json (run with --sync)")
    for jid, j in sorted(jobs.items()):
        if j["chapter"] not in chapters:
            errors.append("jobs/%s.json: chapter %d is not one of the pack's %s" % (jid, j["chapter"], chapters))
        if os.path.exists(os.path.join(base_jobs, jid + ".json")):
            errors.append("jobs/%s.json: the base game already has this job (move it, do not copy)" % jid)
    # files: data only, imported kinds with their .import
    files = source_files(pack_dir)
    for rel in files:
        ext = os.path.splitext(rel)[1].lower()
        if ext not in SOURCE_EXT:
            errors.append("%s: only data files belong in a pack (%s)" % (rel, ", ".join(sorted(SOURCE_EXT))))
        elif ext in IMPORTED_EXT and rel + ".import" not in files:
            errors.append("%s: missing %s.import (open the project in Godot or run --import, then commit it)"
                          % (rel, os.path.basename(rel)))
    # texts
    csv_path = os.path.join(pack_dir, "i18n", "content.csv")
    keys = []
    if os.path.exists(csv_path):
        header, keys = csv_keys(csv_path)
        if header != ["keys"] + LANGS:
            errors.append("i18n/content.csv: header must be keys,%s" % ",".join(LANGS))
        dup = sorted(k for k in set(keys) if keys.count(k) > 1)
        if dup:
            errors.append("i18n/content.csv: duplicate keys (first: %s)" % dup[0])
        base_keys = set()
        for p in base_csv:
            if os.path.exists(p):
                base_keys.update(csv_keys(p)[1])
        clash = sorted(set(keys) & base_keys)
        if clash:
            errors.append("i18n/content.csv: %d keys already in the base game (first: %s)" % (len(clash), clash[0]))
        imp = csv_path + ".import"
        if os.path.exists(imp):
            with open(imp, encoding="utf-8") as f:
                if not re.search(r"^compress=(0|false)\s*$", f.read(), re.M):
                    errors.append("i18n/content.csv.import: compress must be 0 (the game reads the key list); run --sync, then --import")
    else:
        base_keys = set()
        for p in base_csv:
            if os.path.exists(p):
                base_keys.update(csv_keys(p)[1])
    known = set(keys) | base_keys
    for jid in sorted(jobs):
        with open(os.path.join(pack_dir, "jobs", jid + ".json"), encoding="utf-8") as f:
            job = json.load(f)
        for field, key in sorted((job.get("i18n") or {}).items()):
            if key not in known:
                errors.append("jobs/%s.json: text %s (%s) is in no content.csv" % (jid, key, field))
    # arrival scenes
    scenes_path = os.path.join(pack_dir, "arrival_scenes.json")
    if os.path.exists(scenes_path):
        try:
            with open(scenes_path, encoding="utf-8") as f:
                scenes = json.load(f).get("scenes", {})
        except (OSError, ValueError, AttributeError) as e:
            scenes = {}
            errors.append("arrival_scenes.json: %s" % e)
        prefix = "res://packs/%s/" % pack_id
        for jid, scene in sorted(scenes.items()):
            if jid not in jobs:
                errors.append("arrival_scenes.json: %s is not a job of this pack" % jid)
            d = str(scene.get("dir", "")) if isinstance(scene, dict) else ""
            if not d.startswith(prefix):
                errors.append("arrival_scenes.json: %s: dir must be under %s" % (jid, prefix))
            elif not os.path.isdir(os.path.join(pack_dir, d[len(prefix):])):
                errors.append("arrival_scenes.json: %s: folder %s does not exist" % (jid, d))
    return errors


def sync_jobs(pack_dir):
    """Rewrites `jobs` in pack.json from jobs/*.json. True when the file changed."""
    path = os.path.join(pack_dir, "pack.json")
    with open(path, encoding="utf-8") as f:
        pack = json.load(f)
    jobs, errors = derive_jobs(pack_dir)
    if errors:
        sys.exit("\n".join(errors))
    changed = fix_csv_import(pack_dir)
    if pack.get("jobs") == jobs:
        return changed
    pack["jobs"] = jobs
    with open(path, "w", encoding="utf-8") as f:
        f.write(json.dumps(pack, indent=2, ensure_ascii=False) + "\n")
    return True


def fix_csv_import(pack_dir):
    """Godot imports a new CSV with compress=1; the game needs 0 (as game/i18n). True when rewritten."""
    imp = os.path.join(pack_dir, "i18n", "content.csv.import")
    if not os.path.exists(imp):
        return False
    with open(imp, encoding="utf-8") as f:
        text = f.read()
    fixed = re.sub(r"^compress=(1|true)\s*$", "compress=0", text, flags=re.M)
    if fixed == text:
        return False
    with open(imp, "w", encoding="utf-8") as f:
        f.write(fixed)
    print("%s: compress=0 set; run Godot --import again before building" % os.path.relpath(imp, ROOT))
    return True


def content_hash(pack_dir, engine=""):
    """Hash of the pack's source files and the engine major.minor (.translation files are made
    from the CSV by Godot's import and are not sources)."""
    h = hashlib.sha256(("engine:%s\n" % engine).encode())
    for rel in source_files(pack_dir):
        if rel.endswith(".translation"):
            continue
        h.update(("%s:%s\n" % (rel, sha256_file(os.path.join(pack_dir, rel)))).encode())
    return h.hexdigest()[:16]


def check_data_only(pack_id, paths, sources):
    """Errors if the pck holds anything but this pack's data (`sources`: relative source paths)."""
    errors = []
    prefix = "res://packs/%s/" % pack_id
    in_pack = set()
    imported_names = {}
    for rel in sources:
        res = prefix + rel
        imported_names[hashlib.md5(res.encode()).hexdigest()] = os.path.basename(rel)
    for p in paths:
        if p in HOUSEKEEPING:
            continue
        if p.startswith(prefix):
            if ".." in p or os.path.splitext(p)[1].lower() not in PCK_EXT:
                errors.append("%s: not allowed in a data-only content pack: %s" % (pack_id, p))
            in_pack.add(p[len(prefix):])
            continue
        m = IMPORTED_RE.match(p)
        if m and imported_names.get(m.group(2)) == m.group(1):
            continue
        errors.append("%s: not allowed in a data-only content pack: %s" % (pack_id, p))
    for rel in sources:
        ext = os.path.splitext(rel)[1].lower()
        if ext == ".json" and rel not in in_pack:
            errors.append("%s: %s is missing from the pck" % (pack_id, rel))
        elif ext in IMPORTED_EXT and ext != ".csv" and rel + ".import" not in in_pack:
            errors.append("%s: %s.import is missing from the pck (run with --import)" % (pack_id, rel))
        elif ext == ".csv":
            for lang in LANGS:
                tr = "%s.%s.translation" % (rel[:-len(".csv")], lang)
                if tr not in in_pack:
                    errors.append("%s: %s is missing from the pck (run with --import)" % (pack_id, tr))
    return errors


def next_preset_index(text):
    return max([int(n) for n in re.findall(r"^\[preset\.(\d+)\]", text, re.M)] or [-1]) + 1


def godot_engine(godot):
    try:  # "4.7.2.stable.official.ed1daf0bf" -> "4.7"
        return ".".join(subprocess.run([godot, "--version"], capture_output=True, text=True,
                                       check=True).stdout.strip().split(".")[:2])
    except (OSError, subprocess.CalledProcessError):
        sys.exit("cannot run Godot: %s (pass --godot or set GODOT)" % godot)


def load_pack(pack_id):
    with open(os.path.join(PACKS, pack_id, "pack.json"), encoding="utf-8") as f:
        return json.load(f)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--godot", default=os.environ.get("GODOT", "godot"))
    ap.add_argument("--import", dest="do_import", action="store_true", help="run `--import` first (fresh checkout)")
    ap.add_argument("--packs", default="", help="comma list; default: every game/packs/<id>/")
    ap.add_argument("--out", default=os.path.join(GAME, "build", "content"))
    ap.add_argument("--released", default="", help="folder with content_<id>.json of releases that already exist")
    ap.add_argument("--base-url", default=os.environ.get("CONTENT_PACKS_BASE_URL", DEFAULT_BASE_URL))
    ap.add_argument("--write-game-manifest", action="store_true", help="also write game/data/content_packs.json")
    ap.add_argument("--check", action="store_true", help="validate the pack sources and stop")
    ap.add_argument("--sync", action="store_true", help="rewrite `jobs` in every pack.json and stop")
    ap.add_argument("--list", action="store_true", help='print "<id> <version> <tag>" per pack and stop')
    args = ap.parse_args(argv)

    ids = [p for p in args.packs.split(",") if p] or discover()
    if args.sync:
        for pid in ids:
            print("%s: %s" % (pid, "pack.json / imports updated" if sync_jobs(os.path.join(PACKS, pid)) else "up to date"))
        return
    errors = []
    for pid in ids:
        errors += ["%s: %s" % (pid, e) for e in check_source(pid, os.path.join(PACKS, pid))]
    seen = {}
    for pid in ids:
        if errors:
            break
        for jid in load_pack(pid)["jobs"]:
            if jid in seen:
                errors.append("%s: job %s is also in pack %s" % (pid, jid, seen[jid]))
            seen[jid] = pid
    if errors:
        sys.exit("\n".join(errors))
    if args.check:
        print("content packs OK: %s" % (", ".join(ids) if ids else "none"))
        return
    if args.list:
        for pid in ids:
            v = load_pack(pid)["version"]
            print("%s %d %s" % (pid, v, tag_for(pid, v)))
        return

    os.makedirs(args.out, exist_ok=True)
    out = os.path.abspath(args.out)
    manifest = {"schema": SCHEMA, "packs": {}}
    to_build = []
    engine = godot_engine(args.godot) if ids else ""
    for pid in ids:
        pack = load_pack(pid)
        chash = content_hash(os.path.join(PACKS, pid), engine)
        released = os.path.join(args.released, "content_%s.json" % pid) if args.released else ""
        if released and os.path.exists(released):
            with open(released, encoding="utf-8") as f:
                entry = json.load(f)
            if entry.get("content") != chash or entry.get("version") != pack["version"]:
                sys.exit("%s: its sources changed since release %s; raise `version` in game/packs/%s/pack.json"
                         % (pid, tag_for(pid, pack["version"]), pid))
            manifest["packs"][pid] = entry
            print("content_%s.pck  v%d already released (%s)" % (pid, pack["version"], tag_for(pid, pack["version"])))
        else:
            to_build.append((pid, pack, chash))

    if to_build:
        if args.do_import:
            subprocess.run([args.godot, "--headless", "--path", GAME, "--import"], check=True)
        with open(PRESETS, encoding="utf-8") as f:
            original = f.read()
        text = original
        n = next_preset_index(original)
        for i, (pid, _pack, _h) in enumerate(to_build):
            text += PRESET_TEMPLATE.format(n=n + i, id=pid)
        try:
            with open(PRESETS, "w", encoding="utf-8") as f:
                f.write(text)
            for pid, pack, chash in to_build:
                pck = os.path.join(out, "content_%s.pck" % pid)
                if os.path.exists(pck):
                    os.remove(pck)
                subprocess.run([args.godot, "--headless", "--path", GAME, "--export-pack", "Content %s" % pid, pck],
                               check=True, stdout=subprocess.DEVNULL)
                if not os.path.exists(pck):
                    errors.append("%s: Godot did not write %s" % (pid, pck))
                    continue
                pck_engine, paths = read_pck_paths(pck)
                errors += check_data_only(pid, paths, source_files(os.path.join(PACKS, pid)))
                tag = tag_for(pid, pack["version"])
                base_url = args.base_url.replace("{tag}", tag).rstrip("/")
                size = os.path.getsize(pck)
                entry = {
                    "file": "content_%s.pck" % pid,
                    "url": "%s/content_%s.pck" % (base_url, pid),
                    "size": size,
                    "sha256": sha256_file(pck),
                    "godot": "%d.%d" % pck_engine,
                    "version": pack["version"],
                    "min_game": pack["min_game"],
                    "chapters": sorted(pack["chapters"]),
                    "jobs": pack["jobs"],
                    "content": chash,
                }
                manifest["packs"][pid] = entry
                with open(os.path.join(out, "content_%s.json" % pid), "w", encoding="utf-8") as f:
                    f.write(json.dumps(entry, indent=2, sort_keys=True) + "\n")
                print("content_%s.pck  v%d  %.1f MB  %d jobs  sha256 %s" % (pid, pack["version"], size / 1e6,
                                                                           len(pack["jobs"]), entry["sha256"][:16]))
        finally:
            with open(PRESETS, "w", encoding="utf-8") as f:
                f.write(original)
    if errors:
        sys.exit("\n".join(errors))
    text = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    with open(os.path.join(out, "content_packs.json"), "w", encoding="utf-8") as f:
        f.write(text)
    if args.write_game_manifest:
        with open(GAME_MANIFEST, "w", encoding="utf-8") as f:
            f.write(text)
    print("%d pack(s) in content_packs.json, %d built" % (len(manifest["packs"]), len(to_build)))


if __name__ == "__main__":
    main()
